"""Promotion proposal generator — KR-PROMOTE-PHRASEBOOK-FOUNDATION (Deliverable C).

Input: a list of :class:`ReasoningObservation` from the observer.
Output: zero or more :class:`PromotionProposal` records, each
suggesting a new phrasebook entry that would short-circuit a
cluster of recurring operator DMs.

# Pipeline

  1. Embed each observation's ``kora_response`` text via
     :func:`kora_cli.clustering.text_similarity.embed_texts`
     (lexical, $0).
  2. Cluster via greedy agglomerative similarity at
     ``cohesion_threshold`` (default 0.85).
  3. For each cluster ≥ ``min_cluster_size``:
     a. Check answer-consistency: the LARGEST sub-cluster of
        near-identical Kora answers must cover at least
        ``answer_consistency_threshold`` (default 0.75) of the
        outer cluster. Divergent-answer clusters get dropped —
        a proposed template that doesn't match Kora's actual
        behavior is worse than no proposal.
     b. Derive a candidate regex pattern from common
        tokens / phrases.
     c. Derive the reply template from the dominant Kora answer
        (or optionally synthesize via Haiku — one call per
        proposal). Defaults to "dominant answer" because it's
        $0 and forces operator review of any Haiku-synthesized
        text anyway.
     d. Mint a :class:`PromotionProposal` with confidence
        derived from cluster cohesion + answer consistency.

# Cost discipline

Lexical embedder: $0. Optional Haiku reply-template synthesis:
~$0.001 per proposal at default thresholds (5-observation
clusters with consistent answers → maybe 2-5 proposals per cycle
in realistic operator-DM volumes). Per cycle: ≤$0.005. Daily
ceiling: well within the $0.01-0.05/day target.

The bucket's STOP-ASK §4 anticipated "pattern derivation generates
pathological regexes" — we mitigate by **escaping all regex
metacharacters** in the derived pattern and emitting a simple
case-insensitive alternation of the cluster's dominant short
phrases. The phrasebook PUT endpoint's existing validator (PR #177
``phrasebook_editor.validate_entries``) will reject any malformed
regex at approve-time anyway, so the worst case is a rejected
operator approval rather than a runtime regex bomb.
"""

from __future__ import annotations

import logging
import re
import uuid
from collections import Counter
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from typing import Any, Awaitable, Callable, Dict, List, Literal, Optional, Tuple

from kora_cli.clustering.text_similarity import (
    TextEmbedding,
    cluster_by_similarity,
    cosine_similarity,
    embed_texts,
)

from .observer import ReasoningObservation

logger = logging.getLogger(__name__)


ProposalStatus = Literal["pending", "approved", "rejected", "expired"]

# Wire-stable status values — paired with the FE constant CC#2
# adds in KR-FE-PROMOTION-REVIEW-PANEL. Update both sides together
# when extending.
PROPOSAL_STATUS_VALUES: Tuple[ProposalStatus, ...] = (
    "pending",
    "approved",
    "rejected",
    "expired",
)


# Default thresholds — kept conservative so operator isn't flooded
# with marginal proposals on day one. Operator can loosen via the
# cycle's keyword args (cron task reads from env).
DEFAULT_MIN_CLUSTER_SIZE = 5
DEFAULT_COHESION_THRESHOLD = 0.85
DEFAULT_ANSWER_CONSISTENCY_THRESHOLD = 0.75

# Sample-question cap exposed to the operator in the proposal
# review UI. Three is enough to recognize the cluster shape
# without overwhelming the panel.
SAMPLE_QUESTIONS_CAP = 3


@dataclass(frozen=True, slots=True)
class PromotionProposal:
    """Wire-stable proposal shape. Persisted as JSON by
    :mod:`.store` and surfaced via the cockpit API endpoints in
    web_server.py.
    """

    proposal_id: str
    cluster_size: int
    sample_questions: List[str]
    proposed_pattern: str
    proposed_reply_template: str
    proposed_category: str
    confidence: float
    created_at: datetime
    status: ProposalStatus
    review_notes: str = ""
    # KR-PROMOTE-PHRASEBOOK-FOUNDATION — back-references so the
    # cockpit can render the observation context that triggered
    # the proposal without re-running the cycle.
    cluster_caller_session_ids: List[str] = field(default_factory=list)
    # ``haiku_synthesized`` is True when the reply_template was
    # generated by a Haiku call; False when it's the dominant
    # cluster member verbatim. Operator approval UI can flag
    # synthesized text for extra-careful review.
    haiku_synthesized: bool = False


def _format_iso(dt: datetime) -> str:
    return dt.strftime("%Y-%m-%dT%H:%M:%SZ")


def proposal_to_dict(p: PromotionProposal) -> Dict[str, Any]:
    """Serialize a PromotionProposal to a JSON-safe dict for both
    audit emission and on-disk persistence."""
    out = asdict(p)
    out["created_at"] = _format_iso(p.created_at)
    return out


def proposal_from_dict(payload: Dict[str, Any]) -> PromotionProposal:
    """Rehydrate a proposal from its serialized form. Strict
    field-presence (no defaulting of required fields) so a
    malformed file surfaces loudly at load time."""
    ts_raw = payload.get("created_at", "")
    if isinstance(ts_raw, str) and ts_raw:
        if ts_raw.endswith("Z"):
            ts_raw = ts_raw[:-1] + "+00:00"
        created_at = datetime.fromisoformat(ts_raw)
        if created_at.tzinfo is None:
            created_at = created_at.replace(tzinfo=timezone.utc)
    else:
        created_at = datetime.now(timezone.utc)
    return PromotionProposal(
        proposal_id=str(payload["proposal_id"]),
        cluster_size=int(payload["cluster_size"]),
        sample_questions=list(payload.get("sample_questions") or []),
        proposed_pattern=str(payload["proposed_pattern"]),
        proposed_reply_template=str(payload["proposed_reply_template"]),
        proposed_category=str(payload["proposed_category"]),
        confidence=float(payload.get("confidence") or 0.0),
        created_at=created_at,
        status=str(payload.get("status") or "pending"),  # type: ignore[arg-type]
        review_notes=str(payload.get("review_notes") or ""),
        cluster_caller_session_ids=list(
            payload.get("cluster_caller_session_ids") or []
        ),
        haiku_synthesized=bool(payload.get("haiku_synthesized") or False),
    )


